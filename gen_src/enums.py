def enum_xml(iname, vals):
    eid = get("enum." + iname)
    body = []
    body.append('<?xml version="1.0" encoding="UTF-8"?>')
    body.append('<MetaDataObject xmlns="http://v8.1c.ru/8.3/MDClasses" xmlns:app="http://v8.1c.ru/8.2/managed-application/core" xmlns:cfg="http://v8.1c.ru/8.1/data/enterprise/current-config" xmlns:cmi="http://v8.1c.ru/8.2/managed-application/cmi" xmlns:ent="http://v8.1c.ru/8.1/data/enterprise" xmlns:lf="http://v8.1c.ru/8.2/managed-application/logfrm" xmlns:style="http://v8.1c.ru/8.1/data/ui/style" xmlns:sys="http://v8.1c.ru/8.1/data/ui/fonts/system" xmlns:v8="http://v8.1c.ru/8.1/data/core" xmlns:v8ui="http://v8.1c.ru/8.1/data/ui" xmlns:web="http://v8.1c.ru/8.1/data/ui/colors/web" xmlns:win="http://v8.1c.ru/8.1/data/ui/colors/windows" xmlns:xen="http://v8.1c.ru/8.3/xcf/enct">')
    body.append('  <InternalInfo>')
    body.append('    <xen:generator>')
    body.append('      <xen:packageName>ДваРояля</xen:packageName>')
    body.append('    </xen:generator>')
    body.append('  </InternalInfo>')
    body.append('  <Properties>')
    body.append('    <Name>%s</Name>' % iname)
    body.append('    <Synonym>' + syn(iname) + '</Synonym>')
    body.append('    <Comment/>')
    body.append('    <UUID>' + eid + '</UUID>')
    body.append('    <ValueType><v8:Type>xs:string</v8:Type></ValueType>')
    body.append('    <BelongsToUnknownSection>false</BelongsToUnknownSection>')
    for vname, vsyn in vals:
        body.append('    <Value>')
        body.append('      <Name>%s</Name>' % vname)
        body.append('      <Synonym>%s</Synonym>' % vsyn)
        body.append('      <Comment/>')
        body.append('    </Value>')
    body.append('  </Properties>')
    body.append('</MetaDataObject>')
    return "\n".join(body)

