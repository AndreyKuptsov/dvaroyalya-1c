def module_xml(name, md):
    mid = get("commonmodule."+name)
    buf=[HEADER]
    buf.append('  <Properties>')
    buf.append('    <Name>%s</Name>'%name)
    buf.append('    <Synonym>%s</Synonym>'%md["syn"])
    buf.append('    <Comment/>')
    buf.append('    <UUID>%s</UUID>'%mid)
    buf.append('    <Server>%s</Server>'%("true" if md["server"] else "false"))
    buf.append('    <ClientManagedApplication>%s</ClientManagedApplication>'%("true" if md["client"] else "false"))
    buf.append('    <ExternalConnection>%s</ExternalConnection>'%("true" if md["external"] else "false"))
    buf.append('    <ClientOrdinaryApplication>false</ClientOrdinaryApplication>')
    buf.append('    <ServerCall>false</ServerCall>')
    buf.append('    <Privileged>false</Privileged>')
    buf.append('    <ReturnValuesReuse>DontUse</ReturnValuesReuse>')
    buf.append('    <Global>%s</Global>'%("true" if md.get("globalm") else "false"))
    buf.append('    <ClientConnect>false</ClientConnect>')
    buf.append('    <ServerCallForManagedApplication>false</ServerCallForManagedApplication>')
    buf.append('  </Properties>')
    buf.append('</MetaDataObject>')
    return "\n".join(buf)

